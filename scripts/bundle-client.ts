#!/usr/bin/env bun
/**
 * Prebuild the browser bundles into src/generated/ so published packages and
 * compiled binaries don't need client sources, Tailwind, or a bundler at runtime.
 */
import { mkdir, writeFile } from 'fs/promises'
import { join, dirname } from 'path'
import { buildClientBundles } from '../src/assets'

const outDir = join(dirname(import.meta.dir), 'src', 'generated')
await mkdir(outDir, { recursive: true })

const bundles = await buildClientBundles({ editor: true, minify: true })
if (!bundles.editorJs || !bundles.editorCss) throw new Error('Editor bundle build failed')

await writeFile(join(outDir, 'viewer.js.txt'), bundles.viewerJs)
await writeFile(join(outDir, 'editor.js.txt'), bundles.editorJs)
await writeFile(join(outDir, 'editor.css.txt'), bundles.editorCss)
await writeFile(join(outDir, 'client-bundles.ts'), `// Generated by scripts/bundle-client.ts — do not edit
import viewerJs from './viewer.js.txt' with { type: 'text' }
import editorJs from './editor.js.txt' with { type: 'text' }
import editorCss from './editor.css.txt' with { type: 'text' }

export default { viewerJs, editorJs, editorCss } as { viewerJs: string; editorJs: string; editorCss: string }
`)

console.log(`Client bundles written to ${outDir}`)
