#!/usr/bin/env bun
/**
 * Prebuild the browser bundles into src/generated/ so published packages and
 * compiled binaries don't need client sources, Tailwind, or a bundler at runtime.
 */
import { mkdir, writeFile, rm } from 'fs/promises'
import { join, dirname } from 'path'
import { buildClientBundles } from '../src/assets'

const outDir = join(dirname(import.meta.dir), 'src', 'generated')
await rm(outDir, { recursive: true, force: true })
await mkdir(join(outDir, 'files'), { recursive: true })

const { files } = await buildClientBundles({ editor: true, minify: true })
if (!files['editor.js'] || !files['editor.css']) throw new Error('Editor bundle build failed')

// Each file is imported as text so `bun build --compile` embeds it
const names = Object.keys(files).sort()
const imports: string[] = []
const entries: string[] = []
for (const [i, name] of names.entries()) {
  await writeFile(join(outDir, 'files', `${name}.txt`), files[name]!)
  imports.push(`import f${i} from './files/${name}.txt' with { type: 'text' }`)
  entries.push(`  ${JSON.stringify(name)}: f${i},`)
}

await writeFile(join(outDir, 'client-bundles.ts'), `// Generated by scripts/bundle-client.ts — do not edit
${imports.join('\n')}

export default { files: {
${entries.join('\n')}
} } as { files: Record<string, string> }
`)

console.log(`Client bundles written to ${outDir} (${names.length} files)`)
